# ═══════════════════════════════════════════
# 실습 4: 짝수 찾기
# ═══════════════════════════════════════════
# 💭 목표: 1~10 중 짝수만 출력 (2, 4, 6, 8, 10)
# 🐛 실제 결과: 홀수가 나옴
# 🐛 버그: ?

for i in range(1, 11):
    if i % 2 == 1:
        print(i)

# 힌트: % 연산자는 나머지야. 짝수는 2로 나눴을 때 나머지가 몇?


