# ═══════════════════════════════════════════
# 실습 2: 1부터 5까지 더하기
# ═══════════════════════════════════════════
# 💭 목표: 1+2+3+4+5 = 15
# 🐛 실제 결과: 10
# 🐛 버그: ?

total = 0
for i in range(1, 5):
    total = total + i
print(total)

# 힌트: range(1, 5)는 1, 2, 3, 4까지야. 5가 포함될까?


