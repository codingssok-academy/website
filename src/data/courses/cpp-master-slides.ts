import type { Chapter, Page, Unit } from './types';

interface MasterChapterDef {
    id: string;
    chapterNumber: number;
    title: string;
    icon: string;
    description: string;
    base: string;
    startUnitNumber: number;
    unitDefs: Array<{
        title: string;
        subtitle: string;
        type: Unit['type'];
        difficulty: Unit['difficulty'];
        slides: string[];
    }>;
}

function makeSlidePage(base: string, globalSlideNumber: number, title: string): Page {
    const fileName = `${String(globalSlideNumber).padStart(2, '0')}.png`;
    return {
        id: `${base.split('/').pop()}-${fileName}`,
        title,
        type: '페이지',
        content: `<div class="cs-slide-wrap"><img class="cs-slide" src="${base}/${fileName}" alt="${title}" loading="lazy" /></div>`,
    };
}

function makeMasterChapter(def: MasterChapterDef): Chapter {
    let slideNumber = 1;
    const units = def.unitDefs.map((unitDef, index) => {
        const pages = unitDef.slides.map(title => makeSlidePage(def.base, slideNumber++, title));
        return {
            id: `${def.id}-u${String(index + 1).padStart(2, '0')}`,
            unitNumber: def.startUnitNumber + index,
            title: unitDef.title,
            subtitle: unitDef.subtitle,
            type: unitDef.type,
            difficulty: unitDef.difficulty,
            duration: '30분',
            pages,
        };
    });

    return {
        id: def.id,
        chapterNumber: def.chapterNumber,
        title: def.title,
        icon: def.icon,
        description: def.description,
        units,
    };
}

